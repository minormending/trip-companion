#!/usr/bin/env node
/**
 * Materialise map-kit's shared SQL into the platform migration set.
 *
 * Written once and committed as plain SQL, because a migration's checksum has
 * to be stable — a file whose content depends on an environment variable is a
 * file whose hash changes under you.
 *
 *   node scripts/gen-platform.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readKitSql } from '@minormending/map-kit/node/sql'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'platform')

const banner = (name) => `-- Generated by scripts/gen-platform.mjs from @minormending/map-kit.
-- Do not edit once applied: the runner's hash check will refuse it, and it is
-- right to. Add another migration.
--
-- This is the SHARED layer. It is installed once per database and every app
-- schema in that database uses it. See docs/PLATFORM.md.

`

writeFileSync(join(OUT, '0001_profiles.sql'), banner('profiles') + readKitSql('profiles'))

// The rate-limit salt is per database rather than per app: one bucket table,
// one fingerprint. Callers namespace their own keys ('trip:report:<uid>').
writeFileSync(
  join(OUT, '0002_rate_limit.sql'),
  banner('rate_limit') + readKitSql('rate_limit', { APP: 'minormending-platform' }),
)

console.log('wrote supabase/platform/0001_profiles.sql')
console.log('wrote supabase/platform/0002_rate_limit.sql')
